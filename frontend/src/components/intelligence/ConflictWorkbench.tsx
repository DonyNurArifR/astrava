import React, { useEffect, useState } from 'react';
import {
  AlertTriangle,
  GitMerge,
  CheckCircle,
  XCircle,
  RefreshCw,
} from 'lucide-react';
import { api } from '../../api/client';
import type {
  MemoryConflictItem,
} from '../../types/api';
import { ProvenanceBadge } from './ProvenanceBadge';

interface ConflictWorkbenchProps {
  projectId: string;
  onConflictResolved?: () => void;
}

export const ConflictWorkbench: React.FC<ConflictWorkbenchProps> = ({
  projectId,
  onConflictResolved,
}) => {
  const [conflicts, setConflicts] = useState<MemoryConflictItem[]>([]);
  const [selectedConflict, setSelectedConflict] = useState<MemoryConflictItem | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  // Resolution modal state
  const [resolutionStrategy, setResolutionStrategy] = useState<'supersede' | 'reject' | 'merge'>('supersede');
  const [resolutionReason, setResolutionReason] = useState('');
  const [mergedSummary, setMergedSummary] = useState('');
  const [mergedContent, setMergedContent] = useState('');
  const [resolving, setResolving] = useState(false);
  const [resolveError, setResolveError] = useState<string | null>(null);

  const fetchConflicts = () => {
    setLoading(true);
    api.getConflicts(projectId, undefined, 1, 50)
      .then(res => {
        const items = Array.isArray(res) ? res : (res?.items || []);
        setConflicts(items);
        if (items.length > 0 && !selectedConflict) {
          setSelectedConflict(items[0]);
        }
        setLoading(false);
      })
      .catch(err => {
        setError(err.message);
        setLoading(false);
      });
  };

  useEffect(() => {
    if (projectId) {
      fetchConflicts();
    }
  }, [projectId]);

  useEffect(() => {
    if (selectedConflict) {
      setMergedSummary(selectedConflict.summary);
      setMergedContent('');
      setResolutionReason('');
      setResolveError(null);
    }
  }, [selectedConflict]);

  const handleResolve = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!selectedConflict) return;
    if (!resolutionReason.trim()) {
      setResolveError('A resolution reason is required.');
      return;
    }
    if (resolutionStrategy === 'merge' && (!mergedSummary.trim() || !mergedContent.trim())) {
      setResolveError('Merged summary and content are both required for merge strategy.');
      return;
    }

    setResolving(true);
    setResolveError(null);

    try {
      await api.resolveConflict(projectId, selectedConflict.memory_id, {
        resolution: resolutionStrategy,
        reason: resolutionReason.trim(),
        merged_summary: resolutionStrategy === 'merge' ? mergedSummary.trim() : undefined,
        merged_content: resolutionStrategy === 'merge' ? mergedContent.trim() : undefined,
      });

      // Refresh conflicts
      fetchConflicts();
      setSelectedConflict(null);
      if (onConflictResolved) onConflictResolved();
    } catch (err: any) {
      setResolveError(err.message || 'Conflict resolution failed.');
    } finally {
      setResolving(false);
    }
  };

  if (loading) {
    return <div className="p-8 text-center text-slate-400 text-xs">Scanning for memory conflicts...</div>;
  }

  if (error) {
    return (
      <div className="p-4 bg-red-500/10 border border-red-500/30 text-red-600 dark:text-red-400 rounded-xl text-xs flex items-center justify-between">
        <span>{error}</span>
        <button onClick={fetchConflicts} className="hover:underline font-semibold">
          Retry
        </button>
      </div>
    );
  }

  if (conflicts.length === 0) {
    return (
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl p-12 text-center space-y-3">
        <div className="w-12 h-12 rounded-full bg-emerald-500/10 text-emerald-500 flex items-center justify-center mx-auto">
          <CheckCircle size={24} />
        </div>
        <h3 className="font-bold text-slate-900 dark:text-white text-base">
          Zero Detected Conflicts
        </h3>
        <p className="text-xs text-slate-500 dark:text-slate-400 max-w-md mx-auto">
          All active project memories are harmonious and consistent. When contradictory memories are
          generated by agents or operators, they will appear here for review and resolution.
        </p>
      </div>
    );
  }

  return (
    <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
      {/* Conflicts List */}
      <div className="space-y-3">
        <div className="flex items-center justify-between">
          <h3 className="font-bold text-sm text-slate-900 dark:text-white flex items-center gap-2">
            <AlertTriangle className="text-amber-500" size={16} />
            Detected Conflicts ({conflicts.length})
          </h3>
          <button
            onClick={fetchConflicts}
            className="p-1 text-slate-400 hover:text-slate-600 rounded"
            title="Refresh"
          >
            <RefreshCw size={14} />
          </button>
        </div>

        <div className="space-y-2">
          {conflicts.map(c => {
            const isSelected = selectedConflict?.memory_id === c.memory_id;
            return (
              <button
                key={c.memory_id}
                onClick={() => setSelectedConflict(c)}
                className={`w-full text-left p-3.5 rounded-xl border transition-all text-xs ${
                  isSelected
                    ? 'bg-amber-500/10 border-amber-500/40 shadow-xs'
                    : 'bg-white dark:bg-slate-900 border-slate-200 dark:border-slate-800 hover:border-slate-300'
                }`}
              >
                <div className="flex items-center gap-2 mb-1">
                  <span className="font-mono text-[10px] uppercase font-bold text-amber-600 dark:text-amber-400 bg-amber-500/10 px-1.5 py-0.5 rounded">
                    {c.category}
                  </span>
                  <span className="text-[10px] text-slate-400 font-mono">
                    Rev {c.revision}
                  </span>
                </div>
                <p className="font-semibold text-slate-900 dark:text-white line-clamp-1">
                  {c.summary}
                </p>
                <p className="text-[11px] text-slate-500 mt-1 line-clamp-1">
                  Partner: {c.partner_summary || 'Colliding memory assertion'}
                </p>
              </button>
            );
          })}
        </div>
      </div>

      {/* Resolution Workbench Card */}
      <div className="lg:col-span-2 bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl p-6 space-y-6">
        {selectedConflict ? (
          <div>
            <div className="flex items-center justify-between pb-4 border-b border-slate-200 dark:border-slate-800 mb-6">
              <div>
                <h3 className="font-bold text-sm text-slate-900 dark:text-white">
                  Conflict Resolution Workbench
                </h3>
                <p className="text-xs text-slate-500">
                  Select a deterministic strategy to resolve the collision between these two memory records.
                </p>
              </div>
              <span className="font-mono text-xs bg-amber-500/10 text-amber-600 dark:text-amber-400 font-bold px-2.5 py-1 rounded-full border border-amber-500/20">
                Action Required
              </span>
            </div>

            {/* Comparison Cards */}
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
              {/* Record A */}
              <div className="p-4 rounded-xl border border-blue-500/30 bg-blue-50/30 dark:bg-blue-900/10 space-y-2 text-xs">
                <div className="flex items-center justify-between">
                  <span className="font-bold font-mono text-blue-600 dark:text-blue-400">
                    Candidate Record (A)
                  </span>
                  <span className="text-[10px] font-mono text-slate-400">
                    Rev {selectedConflict.revision}
                  </span>
                </div>
                <p className="font-semibold text-slate-900 dark:text-white">
                  {selectedConflict.summary}
                </p>
                <div className="flex items-center gap-2 pt-1">
                  <ProvenanceBadge provenance={selectedConflict.provenance_type} />
                </div>
              </div>

              {/* Record B (Partner) */}
              <div className="p-4 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800/40 space-y-2 text-xs">
                <div className="flex items-center justify-between">
                  <span className="font-bold font-mono text-slate-600 dark:text-slate-400">
                    Existing Partner Record (B)
                  </span>
                  <span className="text-[10px] font-mono text-slate-400">
                    Rev {selectedConflict.partner_revision ?? 1}
                  </span>
                </div>
                <p className="font-semibold text-slate-900 dark:text-white">
                  {selectedConflict.partner_summary || selectedConflict.summary}
                </p>
                <div className="flex items-center gap-2 pt-1">
                  {selectedConflict.partner_provenance_type && (
                    <ProvenanceBadge provenance={selectedConflict.partner_provenance_type} />
                  )}
                </div>
              </div>
            </div>

            {/* Resolution Form */}
            <form onSubmit={handleResolve} className="space-y-4 pt-4 border-t border-slate-200 dark:border-slate-800 text-xs">
              {resolveError && (
                <div className="p-3 bg-red-500/10 border border-red-500/30 rounded-xl text-red-600 dark:text-red-400 text-xs">
                  {resolveError}
                </div>
              )}

              {/* Strategy Selector */}
              <div>
                <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-2">
                  Resolution Strategy
                </label>
                <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
                  <button
                    type="button"
                    onClick={() => setResolutionStrategy('supersede')}
                    className={`p-3 rounded-xl border text-left transition-all ${
                      resolutionStrategy === 'supersede'
                        ? 'bg-blue-600 text-white border-blue-600 shadow-sm'
                        : 'bg-slate-50 dark:bg-slate-800/50 text-slate-700 dark:text-slate-300 border-slate-200 dark:border-slate-700'
                    }`}
                  >
                    <div className="font-bold flex items-center gap-1.5 mb-1">
                      <CheckCircle size={14} /> Supersede
                    </div>
                    <p className={`text-[10px] ${resolutionStrategy === 'supersede' ? 'text-blue-100' : 'text-slate-500'}`}>
                      Keep Candidate A active; supersede Partner B.
                    </p>
                  </button>

                  <button
                    type="button"
                    onClick={() => setResolutionStrategy('reject')}
                    className={`p-3 rounded-xl border text-left transition-all ${
                      resolutionStrategy === 'reject'
                        ? 'bg-red-600 text-white border-red-600 shadow-sm'
                        : 'bg-slate-50 dark:bg-slate-800/50 text-slate-700 dark:text-slate-300 border-slate-200 dark:border-slate-700'
                    }`}
                  >
                    <div className="font-bold flex items-center gap-1.5 mb-1">
                      <XCircle size={14} /> Reject
                    </div>
                    <p className={`text-[10px] ${resolutionStrategy === 'reject' ? 'text-red-100' : 'text-slate-500'}`}>
                      Reject Candidate A; keep Partner B active.
                    </p>
                  </button>

                  <button
                    type="button"
                    onClick={() => setResolutionStrategy('merge')}
                    className={`p-3 rounded-xl border text-left transition-all ${
                      resolutionStrategy === 'merge'
                        ? 'bg-purple-600 text-white border-purple-600 shadow-sm'
                        : 'bg-slate-50 dark:bg-slate-800/50 text-slate-700 dark:text-slate-300 border-slate-200 dark:border-slate-700'
                    }`}
                  >
                    <div className="font-bold flex items-center gap-1.5 mb-1">
                      <GitMerge size={14} /> Merge
                    </div>
                    <p className={`text-[10px] ${resolutionStrategy === 'merge' ? 'text-purple-100' : 'text-slate-500'}`}>
                      Synthesize new revision; supersede both originals.
                    </p>
                  </button>
                </div>
              </div>

              {/* Synthesized fields if merge */}
              {resolutionStrategy === 'merge' && (
                <div className="space-y-3 p-4 bg-purple-500/5 border border-purple-500/20 rounded-xl">
                  <div>
                    <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
                      Synthesized Summary
                    </label>
                    <input
                      type="text"
                      value={mergedSummary}
                      onChange={e => setMergedSummary(e.target.value)}
                      className="w-full text-xs px-3 py-2 bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-lg text-slate-900 dark:text-white"
                      required
                    />
                  </div>
                  <div>
                    <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
                      Synthesized Content Specification
                    </label>
                    <textarea
                      value={mergedContent}
                      onChange={e => setMergedContent(e.target.value)}
                      rows={4}
                      placeholder="Write unified, synthesized specification addressing both assertions..."
                      className="w-full text-xs px-3 py-2 bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-lg text-slate-900 dark:text-white font-mono"
                      required
                    />
                  </div>
                </div>
              )}

              {/* Mandatory Resolution Reason */}
              <div>
                <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
                  Justification / Resolution Reason
                </label>
                <input
                  type="text"
                  value={resolutionReason}
                  onChange={e => setResolutionReason(e.target.value)}
                  placeholder="e.g. Architecture committee ratified Redis Cluster over Standalone"
                  className="w-full text-xs px-3 py-2 bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-lg text-slate-900 dark:text-white"
                  required
                />
              </div>

              {/* Submit */}
              <div className="flex justify-end pt-2">
                <button
                  type="submit"
                  disabled={resolving}
                  className="px-5 py-2 bg-blue-600 hover:bg-blue-700 text-white rounded-lg text-xs font-semibold flex items-center gap-1.5 shadow-sm disabled:opacity-50"
                >
                  {resolving ? 'Resolving Conflict...' : 'Execute Resolution'}
                </button>
              </div>
            </form>
          </div>
        ) : (
          <div className="py-12 text-center text-slate-400 text-xs">
            Select a conflict from the left column to inspect and resolve.
          </div>
        )}
      </div>
    </div>
  );
};
