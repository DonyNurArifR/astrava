import React, { useEffect, useState } from 'react';
import {
  FileText,
  Download,
  Eye,
  X,
  Copy,
  Check,
  FileCode,
  Search,
} from 'lucide-react';
import { api } from '../api/client';
import type { Artifact, Project } from '../types/api';

export const ArtifactsPage: React.FC = () => {
  const [projects, setProjects] = useState<Project[]>([]);
  const [selectedProjectId, setSelectedProjectId] = useState<string>('all');
  const [artifacts, setArtifacts] = useState<Artifact[]>([]);
  const [loading, setLoading] = useState(true);
  const [previewContent, setPreviewContent] = useState<string | null>(null);
  const [previewArtifact, setPreviewArtifact] = useState<Artifact | null>(null);
  const [copied, setCopied] = useState(false);
  const [searchQuery, setSearchQuery] = useState('');
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    api.getProjects().then(projs => {
      setProjects(projs);
      loadAllArtifacts(projs);
    }).catch(err => {
      setError(err.message);
      setLoading(false);
    });
  }, []);

  const loadAllArtifacts = async (projs: Project[]) => {
    setLoading(true);
    try {
      const all: Artifact[] = [];
      for (const p of projs) {
        const pArtifacts = await api.getArtifactsByProject(p.id);
        all.push(...pArtifacts);
      }
      setArtifacts(all);
    } catch (err: any) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  const handlePreview = async (artifact: Artifact) => {
    try {
      const content = await api.previewArtifact(artifact.id);
      setPreviewArtifact(artifact);
      setPreviewContent(content);
      setCopied(false);
    } catch (err: any) {
      alert(`Could not load artifact preview: ${err.message}`);
    }
  };

  const handleCopy = () => {
    if (!previewContent) return;
    navigator.clipboard.writeText(previewContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const filteredArtifacts = artifacts.filter(a => {
    const matchesProject = selectedProjectId === 'all' || a.project_id === selectedProjectId;
    const matchesSearch =
      searchQuery.trim() === '' ||
      a.name.toLowerCase().includes(searchQuery.toLowerCase()) ||
      a.artifact_type.toLowerCase().includes(searchQuery.toLowerCase());
    return matchesProject && matchesSearch;
  });

  return (
    <div className="p-8 max-w-7xl mx-auto space-y-6">
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
        <div>
          <h2 className="text-2xl font-bold text-slate-900 dark:text-white">Artifacts</h2>
          <p className="text-sm text-slate-500 dark:text-slate-400">
            Sandboxed deliverables generated by autonomous workflows (PRDs, specs, scripts, diffs).
          </p>
        </div>

        <div className="flex items-center gap-3 w-full sm:w-auto">
          {/* Project filter */}
          <select
            value={selectedProjectId}
            onChange={e => setSelectedProjectId(e.target.value)}
            className="bg-white dark:bg-slate-900 border border-slate-300 dark:border-slate-700 text-xs rounded-lg p-2 text-slate-700 dark:text-slate-300 focus:outline-none"
          >
            <option value="all">All Projects</option>
            {projects.map(p => (
              <option key={p.id} value={p.id}>
                {p.name}
              </option>
            ))}
          </select>

          {/* Search */}
          <div className="relative flex-1 sm:w-56">
            <Search size={14} className="absolute left-2.5 top-2.5 text-slate-400" />
            <input
              type="text"
              placeholder="Search artifacts..."
              value={searchQuery}
              onChange={e => setSearchQuery(e.target.value)}
              className="w-full pl-8 pr-3 py-1.5 bg-white dark:bg-slate-900 border border-slate-300 dark:border-slate-700 rounded-lg text-xs text-slate-900 dark:text-white focus:outline-none"
            />
          </div>
        </div>
      </div>

      {error && (
        <div className="p-4 bg-red-500/10 border border-red-500/30 text-red-600 dark:text-red-400 rounded-xl text-sm">
          {error}
        </div>
      )}

      {loading ? (
        <div className="p-12 text-center text-slate-400 text-sm">Loading artifact directory...</div>
      ) : filteredArtifacts.length === 0 ? (
        <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl p-12 text-center text-slate-400 space-y-2">
          <FileText size={32} className="mx-auto text-slate-300" />
          <p className="text-sm">No artifacts registered yet.</p>
        </div>
      ) : (
        <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl shadow-sm overflow-hidden">
          <table className="w-full text-left text-xs">
            <thead className="bg-slate-50 dark:bg-slate-800/60 border-b border-slate-200 dark:border-slate-800 text-slate-500 font-bold uppercase tracking-wider">
              <tr>
                <th className="py-3 px-4">Artifact Name</th>
                <th className="py-3 px-4">Type</th>
                <th className="py-3 px-4">Size</th>
                <th className="py-3 px-4">Storage Path</th>
                <th className="py-3 px-4">Registered At</th>
                <th className="py-3 px-4 text-right">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
              {filteredArtifacts.map(art => (
                <tr
                  key={art.id}
                  className="hover:bg-slate-50 dark:hover:bg-slate-800/40 transition-colors"
                >
                  <td className="py-3.5 px-4 font-semibold text-slate-900 dark:text-white flex items-center gap-2">
                    <FileCode size={16} className="text-blue-500 shrink-0" />
                    <span>{art.name}</span>
                  </td>
                  <td className="py-3.5 px-4">
                    <span className="px-2 py-0.5 rounded text-[10px] font-bold uppercase bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300">
                      {art.artifact_type}
                    </span>
                  </td>
                  <td className="py-3.5 px-4 font-mono text-slate-500">
                    {(art.file_size_bytes / 1024).toFixed(1)} KB
                  </td>
                  <td className="py-3.5 px-4 font-mono text-slate-400 text-[11px] truncate max-w-xs">
                    {art.file_path}
                  </td>
                  <td className="py-3.5 px-4 text-slate-500">
                    {new Date(art.created_at).toLocaleDateString()}
                  </td>
                  <td className="py-3.5 px-4 text-right space-x-2">
                    <button
                      onClick={() => handlePreview(art)}
                      className="px-2.5 py-1 bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 dark:hover:bg-slate-700 rounded text-slate-700 dark:text-slate-300 font-medium inline-flex items-center gap-1"
                    >
                      <Eye size={12} />
                      <span>Preview</span>
                    </button>
                    <a
                      href={api.getDownloadUrl(art.id)}
                      download={art.name}
                      className="px-2.5 py-1 bg-blue-600 hover:bg-blue-500 text-white rounded font-medium inline-flex items-center gap-1"
                    >
                      <Download size={12} />
                      <span>Download</span>
                    </a>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {/* Preview Modal */}
      {previewContent !== null && previewArtifact && (
        <div className="fixed inset-0 bg-slate-950/60 backdrop-blur-xs flex items-center justify-center p-4 z-50">
          <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl max-w-3xl w-full p-6 shadow-xl space-y-4 max-h-[85vh] flex flex-col">
            <div className="flex items-center justify-between border-b border-slate-200 dark:border-slate-800 pb-3">
              <div className="flex items-center gap-2">
                <FileCode size={18} className="text-blue-500" />
                <h3 className="font-bold text-sm text-slate-900 dark:text-white font-mono">
                  {previewArtifact.name}
                </h3>
              </div>
              <div className="flex items-center gap-2">
                <button
                  onClick={handleCopy}
                  className="px-2.5 py-1 bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 text-slate-700 dark:text-slate-300 rounded text-xs flex items-center gap-1 font-medium"
                >
                  {copied ? <Check size={12} className="text-emerald-500" /> : <Copy size={12} />}
                  <span>{copied ? 'Copied' : 'Copy'}</span>
                </button>
                <button
                  onClick={() => {
                    setPreviewContent(null);
                    setPreviewArtifact(null);
                  }}
                  className="text-slate-400 hover:text-slate-900 dark:hover:text-white p-1 rounded"
                >
                  <X size={18} />
                </button>
              </div>
            </div>

            <pre className="flex-1 bg-slate-950 text-slate-200 p-4 rounded-lg overflow-auto font-mono text-xs whitespace-pre-wrap leading-relaxed border border-slate-800">
              {previewContent}
            </pre>
          </div>
        </div>
      )}
    </div>
  );
};
